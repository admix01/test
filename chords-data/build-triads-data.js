// Builds the compact TRIADS_DATA table embedded in ../index.html from
// data/triads.json (1,114 positions: root x quality x string-group x
// inversion, see FONCTIONNEMENT_ACCORDS_TRIADES.txt section 3).
//
// Trims each position down to {r,q,i,s,f} (root index, quality code,
// inversion code, string group, frets) — notes/intervals/midi are all
// re-derivable client-side from the frets + tuning, so they aren't stored.
//
// Usage: node build-triads-data.js > triads-data.snippet.js

const fs = require('fs');
const path = require('path');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/triads.json'), 'utf8'));

const NOTE_NAMES = ['C','C#','D','D#','E','F','F#','G','G#','A','A#','B'];
const rootIdx = {}; NOTE_NAMES.forEach((n, i) => rootIdx[n] = i);
const Q = { major: 'maj', minor: 'min', diminished: 'dim', augmented: 'aug' };
const INV = { root: 'r', first: 'f', second: 's' };

const trimmed = data.positions.map((p) => ({
  r: rootIdx[p.root],
  q: Q[p.quality],
  i: INV[p.inversion],
  s: p.strings,
  f: p.frets_low_to_high,
}));

process.stderr.write(`positions: ${trimmed.length}\n`);
process.stdout.write('// Auto-generated by chords-data/build-triads-data.js — do not hand-edit.\n');
process.stdout.write('// Triad positions (root/first/second inversion, 4 adjacent-string groups) from data/triads.json.\n');
process.stdout.write('const TRIADS_DATA = ' + JSON.stringify(trimmed) + ';\n');
