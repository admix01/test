// Builds the compact REAL_POSITIONS table embedded in ../index.html from
// data/chords.json — the site's cleaned, canonical chord database (1,360
// chord names, positions merged/deduped, single-string and fingering-typo
// "chords" already removed — see FONCTIONNEMENT_ACCORDS_TRIADES.txt).
//
// For each root we look up the canonical name directly (e.g. "C", "Cm",
// "C7", "Cmaj9"...) instead of free-text parsing. A theory check is kept
// as a safety net even though the source is already cleaned: each quality
// declares which pitch classes MUST be present (req) and which MAY
// additionally be present (opt, e.g. the 5th is almost always droppable);
// any note outside req+opt marks the position as a bad transcription and
// drops it. Keeps the top 5 positions per root+quality (by usage_count,
// preferring compact/open fingerings) and prints a JS snippet ready to
// paste into index.html.
//
// Usage: node build-curated-positions.js > curated-positions.snippet.js

const fs = require('fs');
const path = require('path');
const chords = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/chords.json'), 'utf8'));

const NOTE_NAMES = ['C','C#','D','D#','E','F','F#','G','G#','A','A#','B'];

// quality key -> { suffix: canonical name suffix, req: must-have pitch classes, opt: allowed extra pitch classes }
const QUALS = {
  maj:   { suffix:'',      req:[0,4],        opt:[7] },
  min:   { suffix:'m',     req:[0,3],        opt:[7] },
  '5':   { suffix:'5',     req:[0,7],        opt:[] },
  '7':   { suffix:'7',     req:[0,4,10],     opt:[7] },
  maj7:  { suffix:'maj7',  req:[0,4,11],     opt:[7] },
  min7:  { suffix:'m7',    req:[0,3,10],     opt:[7] },
  '6':   { suffix:'6',     req:[0,4,9],      opt:[7] },
  m6:    { suffix:'m6',    req:[0,3,9],      opt:[7] },
  dim:   { suffix:'dim',   req:[0,3,6],      opt:[] },
  dim7:  { suffix:'dim7',  req:[0,3,6,9],    opt:[] },
  aug:   { suffix:'aug',   req:[0,4,8],      opt:[] },
  sus2:  { suffix:'sus2',  req:[0,2,7],      opt:[] },
  sus4:  { suffix:'sus4',  req:[0,5,7],      opt:[] },
  add9:  { suffix:'add9',  req:[0,4,2],      opt:[7] },
  madd9: { suffix:'madd9', req:[0,3,2],      opt:[7] },
  '9':   { suffix:'9',     req:[0,4,10,2],   opt:[7] },
  m9:    { suffix:'m9',    req:[0,3,10,2],   opt:[7] },
  maj9:  { suffix:'maj9',  req:[0,4,11,2],   opt:[7] },
  m7b5:  { suffix:'m7b5',  req:[0,3,6,10],   opt:[] },
  mMaj7: { suffix:'mMaj7', req:[0,3,11],     opt:[7] },
  '7#9': { suffix:'7#9',   req:[0,4,10,3],   opt:[7] },
  '7b9': { suffix:'7b9',   req:[0,4,10,1],   opt:[7] },
  '7#5': { suffix:'7#5',   req:[0,4,8,10],   opt:[] },
  '7b5': { suffix:'7b5',   req:[0,4,6,10],   opt:[] },
  '13':  { suffix:'13',    req:[0,4,10,9],   opt:[7,2] },
};

const STRING_OPEN = [4,9,2,7,11,4]; // low E, A, D, G, B, high e

function isTheoreticallyValid(frets, root, quality) {
  if (!frets.every(f => f === null || (Number.isInteger(f) && f >= 0 && f <= 24))) return false;
  const tones = new Set();
  let hasRoot = false, soundingCount = 0;
  frets.forEach((f, i) => {
    if (f === null) return;
    soundingCount++;
    const interval = ((STRING_OPEN[i] + f) % 12 - root + 12) % 12;
    tones.add(interval);
    if (interval === 0) hasRoot = true;
  });
  if (soundingCount < 3 || !hasRoot) return false;
  const { req, opt } = QUALS[quality];
  if (req.some(x => !tones.has(x))) return false;
  const allowed = new Set([...req, ...opt]);
  if ([...tones].some(x => !allowed.has(x))) return false;
  return true;
}

const TOP_N = 5;
const output = {};
let cellsWithData = 0, totalPositions = 0;

for (let r = 0; r < 12; r++) {
  output[r] = {};
  for (const q in QUALS) {
    const key = NOTE_NAMES[r] + QUALS[q].suffix;
    const positions = chords[key];
    if (!positions) continue;
    const valid = positions.filter(p => isTheoreticallyValid(p.frets_low_to_high, r, q));
    if (!valid.length) continue;
    valid.sort((a, b) => {
      const score = (p) => (p.playable_span_4 ? 0 : 1000) - Math.min(p.usage_count, 999999);
      return score(a) - score(b);
    });
    output[r][q] = valid.slice(0, TOP_N).map((p) => ({ f: p.frets_low_to_high, u: p.usage_count, s: p.song_or_track_count }));
    cellsWithData++;
    totalPositions += output[r][q].length;
  }
}

process.stderr.write(`cells with data: ${cellsWithData} / ${12 * Object.keys(QUALS).length}\n`);
process.stderr.write(`total positions kept: ${totalPositions}\n`);

process.stdout.write('// Auto-generated by chords-data/build-curated-positions.js — do not hand-edit.\n');
process.stdout.write('// Real chord voicings distilled from data/chords.json (cleaned, canonical), ranked by usage.\n');
process.stdout.write('const REAL_POSITIONS = ' + JSON.stringify(output) + ';\n');
