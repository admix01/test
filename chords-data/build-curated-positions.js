// Builds the compact REAL_POSITIONS table embedded in ../index.html from
// chord_positions_by_name.json (DadaGP, aggregated by chord label).
//
// DadaGP labels are free-text tab transcriptions ("C#m7", "#Cm(4)", "Am (normal
// tune)", raw fret digits used as a label by mistake, slash/extended chords...).
// This script keeps only labels that parse cleanly into one of the site's
// 12 known chord qualities, re-derives the actual pitch classes from the
// fret shape, and drops any position whose sounding notes don't match the
// chord it's filed under (~8% of the raw data — bad tab transcriptions).
// The top 5 positions per root+quality (by usage, preferring compact fingerings)
// are kept and printed as a JS snippet ready to paste into index.html.
//
// Usage: node build-curated-positions.js > curated-positions.snippet.js

const fs = require('fs');
const path = require('path');
const grouped = JSON.parse(fs.readFileSync(path.join(__dirname, 'chord_positions_by_name.json'), 'utf8'));

const SEMI = { C:0,'C#':1,Db:1,D:2,'D#':3,Eb:3,E:4,Fb:4,'E#':5,F:5,'F#':6,Gb:6,G:7,'G#':8,Ab:8,A:9,'A#':10,Bb:10,B:11,Cb:11,'B#':0 };
const NOTE_NAMES = ['C','C#','D','D#','E','F','F#','G','G#','A','A#','B'];
const QUALALIAS = {
  '':'maj','maj':'maj','M':'maj',
  'm':'min','min':'min','mi':'min',
  '7':'7','dom7':'7',
  'maj7':'maj7','M7':'maj7','7M':'maj7','ma7':'maj7',
  'm7':'min7','min7':'min7','mi7':'min7',
  '6':'6','maj6':'6','M6':'6',
  'm6':'m6','min6':'m6',
  'dim':'dim','o':'dim',
  'dim7':'dim7','o7':'dim7',
  'aug':'aug','+':'aug',
  'sus2':'sus2',
  'sus4':'sus4','sus':'sus4',
};
const QUALS = ['maj','min','7','maj7','min7','6','m6','dim','dim7','aug','sus2','sus4'];
const INTERVALS = {
  maj:[0,4,7], min:[0,3,7], '7':[0,4,7,10], maj7:[0,4,7,11], min7:[0,3,7,10],
  sus2:[0,2,7], sus4:[0,5,7], '6':[0,4,7,9], m6:[0,3,7,9], dim:[0,3,6],
  dim7:[0,3,6,9], aug:[0,4,8],
};
const STRING_OPEN = [4,9,2,7,11,4]; // low E, A, D, G, B, high e

function parseRoot(label) {
  const m = label.match(/^(#|b)?([A-Ga-g])(#|b)?/);
  if (!m) return null;
  const [, prefixAcc, letter, suffixAcc] = m;
  let noteStr = letter.toUpperCase();
  if (prefixAcc === '#') noteStr += '#';
  else if (prefixAcc === 'b') noteStr += 'b';
  else if (suffixAcc) noteStr += suffixAcc;
  const semi = SEMI[noteStr];
  return semi === undefined ? null : { semi, consumedLen: m[0].length };
}

function parseChordLabel(label) {
  const root = parseRoot(label);
  if (!root) return null;
  let rest = label.slice(root.consumedLen).split('/')[0].split('(')[0].trim();
  const quality = QUALALIAS[rest];
  return quality ? { root: root.semi, quality } : null;
}

function isTheoreticallyValid(frets, root, quality) {
  if (!frets.every(f => f === null || (Number.isInteger(f) && f >= 0 && f <= 20))) return false;
  const tones = new Set();
  let hasRoot = false, soundingCount = 0;
  frets.forEach((f, i) => {
    if (f === null) return;
    soundingCount++;
    const interval = ((STRING_OPEN[i] + f) % 12 - root + 12) % 12;
    tones.add(interval);
    if (interval === 0) hasRoot = true;
  });
  if (soundingCount < 3 || !hasRoot) return false;
  const expected = INTERVALS[quality];
  if (expected.some(x => x !== 7 && !tones.has(x))) return false; // 5th is commonly omitted, tolerate that
  if ([...tones].some(x => !expected.includes(x))) return false; // any other stray tone -> likely a mistranscription
  return true;
}

const cells = {};
for (let r = 0; r < 12; r++) { cells[r] = {}; for (const q of QUALS) cells[r][q] = new Map(); }

for (const name of Object.keys(grouped)) {
  const parsed = parseChordLabel(name);
  if (!parsed) continue;
  const bucket = cells[parsed.root][parsed.quality];
  for (const pos of grouped[name]) {
    if (!isTheoreticallyValid(pos.frets_low_to_high, parsed.root, parsed.quality)) continue;
    const existing = bucket.get(pos.shape);
    if (!existing) bucket.set(pos.shape, { ...pos });
    else { existing.usage_count += pos.usage_count; existing.song_or_track_count += pos.song_or_track_count; }
  }
}

const TOP_N = 5;
const output = {};
for (let r = 0; r < 12; r++) {
  output[r] = {};
  for (const q of QUALS) {
    const arr = Array.from(cells[r][q].values());
    arr.sort((a, b) => {
      const score = (p) => (p.playable_span_4 ? 0 : 1000) + (p.open_plus_high_position ? 500 : 0) - Math.min(p.usage_count, 999999);
      return score(a) - score(b);
    });
    const top = arr.slice(0, TOP_N).map((p) => ({ f: p.frets_low_to_high, u: p.usage_count, s: p.song_or_track_count }));
    if (top.length) output[r][q] = top;
  }
}

process.stdout.write('// Auto-generated by chords-data/build-curated-positions.js — do not hand-edit.\n');
process.stdout.write('// Real chord voicings distilled from DadaGP tab data, ranked by usage, theory-validated.\n');
process.stdout.write('const REAL_POSITIONS = ' + JSON.stringify(output) + ';\n');
