// Builds the compact SCALES_DATA table embedded in ../index.html from
// data/scales.json (43 scale formulas, see FONCTIONNEMENT_GAMMES.txt).
//
// The source is already tiny (~10KB) so nothing is trimmed — kept as an
// ordered array (family grouping is done client-side) with short keys.
//
// Usage: node build-scales-data.js > scales-data.snippet.js

const fs = require('fs');
const path = require('path');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/scales.json'), 'utf8'));

const FAMILY_LABELS = {
  diatonic: 'Diatoniques',
  minor: 'Mineures',
  pentatonic: 'Pentatoniques',
  blues: 'Blues',
  majorModes: 'Modes de la majeure',
  melodicMinorModes: 'Modes de la mineure mélodique',
  harmonicMinorModes: 'Modes de la mineure harmonique',
  world: 'Gammes du monde',
  symmetric: 'Symétriques',
  bebop: 'Bebop',
  pentatonicWorld: 'Pentatoniques du monde',
  hexatonic: 'Hexatoniques',
  other: 'Autres',
};

const scales = Object.keys(data.scales).map((key) => {
  const s = data.scales[key];
  return {
    key,
    name: s.name,
    short: s.shortName,
    family: s.family,
    familyLabel: FAMILY_LABELS[s.family] || s.family,
    intervals: s.intervals,
    degrees: s.degreeLabels,
    aliases: s.aliases,
    desc: s.description,
  };
});

process.stderr.write(`scales: ${scales.length}\n`);
process.stdout.write('// Auto-generated by chords-data/build-scales-data.js — do not hand-edit.\n');
process.stdout.write('// Scale formulas from data/scales.json.\n');
process.stdout.write('const SCALES_DATA = ' + JSON.stringify(scales) + ';\n');
